// 無座標視為不在框內（呼叫端多半要據此重查）；未列出的縣市一律放行。
export function inCity(city, geo) {
  if (!geo || geo.lat == null || geo.lng == null) return false;
  const b = CITY_BBOX[city];
  if (!b) return true;
  return geo.lat >= b[0] && geo.lat <= b[1] && geo.lng >= b[2] && geo.lng <= b[3];
}
